"""
3dGarments AI Training Script
=============================

Trains a body-measurement model using perfect ground truth generated by
tools/train/generate_training_data.js.

Input:  4 images per sample (front, ¾, side, back) + optional body proportions
Output: bust, waist, hips, thighs, weight, BMI

Usage:
    pip install torch torchvision tqdm
    python tools/train/train_model.py --dataset training_dataset.json --epochs 100 --device cuda

The script:
  - Loads training_dataset.json (data URLs for images + exact measurements)
  - Splits 80/10/10 train/val/test
  - Trains a ResNet-based multi-view regressor
  - Saves best checkpoint to best_model.pt
  - Logs train/val loss every epoch
  - Can run for as many epochs as you want (5+ hours if desired)

Run this on YOUR machine with YOUR GPU. I cannot execute it — you do.
"""

import argparse
import json
import base64
import io
import math
import os
import random
from datetime import datetime
from pathlib import Path

import numpy as np
import torch
import torch.nn as nn
from torch.utils.data import Dataset, DataLoader, random_split
from torchvision import models, transforms
from PIL import Image
from tqdm import tqdm


# ---------------------------------------------------------------------------
# Dataset
# ---------------------------------------------------------------------------

class BodyMeasurementDataset(Dataset):
    """
    Loads samples from training_dataset.json.
    Each sample has 4 images (front, three, side, back) as data URLs
    and exact ground-truth measurements.
    """

    MEASURE_KEYS = [
        "chest_cm",   # bust
        "waist_cm",
        "hips_cm",
        "thigh_cm",
        "weight_kg",
        "bmi",
    ]

    def __init__(self, dataset_path, image_size=224, augment=True):
        with open(dataset_path, "r") as f:
            data = json.load(f)

        self.samples = data["samples"]
        self.image_size = image_size
        self.augment = augment

        # Normalization stats (ImageNet defaults; recompute on your data if desired)
        self.normalize = transforms.Normalize(
            mean=[0.485, 0.456, 0.406],
            std=[0.229, 0.224, 0.225],
        )

        # Build transform pipeline
        train_tf = [
            transforms.Resize((image_size, image_size)),
        ]
        if augment:
            train_tf += [
                transforms.RandomHorizontalFlip(p=0.5),
                transforms.RandomRotation(degrees=5),
                transforms.ColorJitter(brightness=0.1, contrast=0.1, saturation=0.1),
            ]
        train_tf += [
            transforms.ToTensor(),
            self.normalize,
        ]
        self.transform = transforms.Compose(train_tf)

        # Pre-compute measurement statistics for target normalization
        self.means = {}
        self.stds = {}
        for k in self.MEASURE_KEYS:
            vals = [s["measurements"].get(k, 0.0) for s in self.samples]
            arr = np.array(vals, dtype=np.float32)
            self.means[k] = float(arr.mean())
            self.stds[k] = float(arr.std() + 1e-6)

    def __len__(self):
        return len(self.samples)

    def _decode_image(self, data_url):
        """Convert a data:image/png;base64,... string to a PIL Image."""
        header, b64 = data_url.split(",", 1)
        img_bytes = base64.b64decode(b64)
        img = Image.open(io.BytesIO(img_bytes)).convert("RGB")
        return img

    def __getitem__(self, idx):
        sample = self.samples[idx]
        images = sample["images"]

        # Load all 4 angles
        angle_order = ["front", "three", "side", "back"]
        imgs = []
        for angle in angle_order:
            img = self._decode_image(images[angle])
            img = self.transform(img)
            imgs.append(img)
        # Stack: (4, 3, H, W)
        imgs = torch.stack(imgs, dim=0)

        # Target measurements
        targets = []
        for k in self.MEASURE_KEYS:
            v = sample["measurements"].get(k, 0.0)
            # z-score normalize
            v = (v - self.means[k]) / self.stds[k]
            targets.append(v)
        targets = torch.tensor(targets, dtype=torch.float32)

        # Optional: include raw proportions as auxiliary input
        props = sample["proportions"]
        prop_vec = torch.tensor([
            props.get("width", 0.0),
            props.get("height", 0.0),
            props.get("fat", 0.0),
            props.get("muscle", 0.0),
            1.0 if props.get("sex") == "male" else 0.0,
        ], dtype=torch.float32)

        return {
            "images": imgs,        # (4, 3, H, W)
            "proportions": prop_vec,  # (5,)
            "targets": targets,    # (6,)
            "sample_id": sample.get("id", str(idx)),
        }


# ---------------------------------------------------------------------------
# Model
# ---------------------------------------------------------------------------

class MultiViewBodyRegressor(nn.Module):
    """
    Takes 4 views of the same body (front, three, side, back) and regresses
    6 measurements: bust, waist, hips, thighs, weight, BMI.

    Architecture:
      - Shared ResNet-18 backbone processes each view independently
      - View features are pooled and concatenated
      - Optional proportion vector is concatenated
      - MLP head regresses the 6 measurements
    """

    def __init__(self, use_proportions=True, pretrained=True):
        super().__init__()
        self.use_proportions = use_proportions

        # Shared backbone: ResNet-18 without the final FC
        backbone = models.resnet18(weights=models.ResNet18_Weights.DEFAULT if pretrained else None)
        self.backbone = nn.Sequential(*list(backbone.children())[:-1])  # (B, 512, 1, 1)
        backbone_out = 512

        # Per-view feature dim
        self.view_dim = backbone_out

        if use_proportions:
            prop_dim = 5
        else:
            prop_dim = 0

        # Regression head
        head_in = backbone_out * 4 + prop_dim
        self.head = nn.Sequential(
            nn.Linear(head_in, 512),
            nn.ReLU(inplace=True),
            nn.Dropout(0.3),
            nn.Linear(512, 256),
            nn.ReLU(inplace=True),
            nn.Dropout(0.3),
            nn.Linear(256, 6),  # 6 measurements
        )

    def forward(self, images, proportions=None):
        """
        images: (B, 4, 3, H, W) — 4 views per sample
        proportions: (B, 5) optional
        returns: (B, 6)
        """
        B, V, C, H, W = images.shape
        # Flatten batch & view for backbone
        x = images.view(B * V, C, H, W)
        feats = self.backbone(x)  # (B*V, 512, 1, 1)
        feats = feats.view(B * V, -1)  # (B*V, 512)
        feats = feats.view(B, V, -1)  # (B, 4, 512)
        feats = feats.reshape(B, -1)  # (B, 2048)

        if self.use_proportions and proportions is not None:
            feats = torch.cat([feats, proportions], dim=1)

        out = self.head(feats)
        return out


# ---------------------------------------------------------------------------
# Training
# ---------------------------------------------------------------------------

def denormalize_targets(normalized, means, stds, keys):
    """Convert z-score normalized predictions back to original units."""
    out = {}
    for i, k in enumerate(keys):
        out[k] = normalized[:, i] * stds[k] + means[k]
    return out


def compute_metrics(pred, target, means, stds, keys):
    """Compute MAE in original units for each measurement."""
    pred_denorm = denormalize_targets(pred, means, stds, keys)
    target_denorm = denormalize_targets(target, means, stds, keys)
    mae = {}
    for i, k in enumerate(keys):
        mae[k] = torch.abs(pred_denorm[:, i] - target_denorm[:, i]).mean().item()
    return mae


def train_epoch(model, loader, optimizer, criterion, device):
    model.train()
    total_loss = 0.0
    n = 0
    for batch in tqdm(loader, desc="train", leave=False):
        images = batch["images"].to(device)      # (B, 4, 3, H, W)
        props = batch["proportions"].to(device)  # (B, 5)
        targets = batch["targets"].to(device)    # (B, 6)

        optimizer.zero_grad()
        preds = model(images, props)
        loss = criterion(preds, targets)
        loss.backward()
        optimizer.step()

        total_loss += loss.item() * images.size(0)
        n += images.size(0)
    return total_loss / n


def validate(model, loader, criterion, device, means, stds, keys):
    model.eval()
    total_loss = 0.0
    n = 0
    all_mae = {k: 0.0 for k in keys}
    with torch.no_grad():
        for batch in tqdm(loader, desc="val", leave=False):
            images = batch["images"].to(device)
            props = batch["proportions"].to(device)
            targets = batch["targets"].to(device)

            preds = model(images, props)
            loss = criterion(preds, targets)

            total_loss += loss.item() * images.size(0)
            n += images.size(0)

            mae = compute_metrics(preds, targets, means, stds, keys)
            for k in keys:
                all_mae[k] += mae[k] * images.size(0)

    avg_loss = total_loss / n
    avg_mae = {k: v / n for k, v in all_mae.items()}
    return avg_loss, avg_mae


def main():
    parser = argparse.ArgumentParser(description="Train body-measurement AI")
    parser.add_argument("--dataset", type=str, required=True,
                        help="Path to training_dataset.json")
    parser.add_argument("--epochs", type=int, default=100,
                        help="Number of training epochs")
    parser.add_argument("--batch-size", type=int, default=16,
                        help="Batch size")
    parser.add_argument("--lr", type=float, default=1e-4,
                        help="Learning rate")
    parser.add_argument("--device", type=str, default="cuda",
                        help="cuda or cpu")
    parser.add_argument("--image-size", type=int, default=224,
                        help="Input image resolution")
    parser.add_argument("--no-proportions", action="store_true",
                        help="Disable proportion auxiliary input")
    parser.add_argument("--seed", type=int, default=42,
                        help="Random seed")
    parser.add_argument("--checkpoint-every", type=int, default=10,
                        help="Save checkpoint every N epochs")
    parser.add_argument("--output-dir", type=str, default="./checkpoints",
                        help="Directory to save checkpoints")
    args = parser.parse_args()

    # Seed
    random.seed(args.seed)
    np.random.seed(args.seed)
    torch.manual_seed(args.seed)
    if args.device == "cuda" and torch.cuda.is_available():
        torch.cuda.manual_seed_all(args.seed)

    device = torch.device(args.device if torch.cuda.is_available() else "cpu")
    print(f"Using device: {device}")

    # Output dir
    out_dir = Path(args.output_dir)
    out_dir.mkdir(parents=True, exist_ok=True)

    # Dataset
    print(f"Loading dataset: {args.dataset}")
    full_dataset = BodyMeasurementDataset(args.dataset, image_size=args.image_size, augment=True)

    # Create a non-augmented version for val/test
    val_dataset = BodyMeasurementDataset(args.dataset, image_size=args.image_size, augment=False)

    n = len(full_dataset)
    n_train = int(0.8 * n)
    n_val = int(0.1 * n)
    n_test = n - n_train - n_val

    train_idx, val_idx, test_idx = random_split(
        range(n), [n_train, n_val, n_test],
        generator=torch.Generator().manual_seed(args.seed)
    )

    # Subset with appropriate transforms
    train_subset = torch.utils.data.Subset(full_dataset, train_idx)
    val_subset = torch.utils.data.Subset(val_dataset, val_idx)
    test_subset = torch.utils.data.Subset(val_dataset, test_idx)

    train_loader = DataLoader(train_subset, batch_size=args.batch_size, shuffle=True,
                              num_workers=4, pin_memory=True)
    val_loader = DataLoader(val_subset, batch_size=args.batch_size, shuffle=False,
                            num_workers=4, pin_memory=True)
    test_loader = DataLoader(test_subset, batch_size=args.batch_size, shuffle=False,
                             num_workers=4, pin_memory=True)

    print(f"Dataset: {n} samples -> train={n_train}, val={n_val}, test={n_test}")

    # Model
    model = MultiViewBodyRegressor(
        use_proportions=not args.no_proportions,
        pretrained=True,
    ).to(device)

    criterion = nn.MSELoss()
    optimizer = torch.optim.Adam(model.parameters(), lr=args.lr, weight_decay=1e-4)
    scheduler = torch.optim.lr_scheduler.ReduceLROnPlateau(
        optimizer, mode="min", factor=0.5, patience=5, verbose=True
    )

    keys = BodyMeasurementDataset.MEASURE_KEYS
    means = full_dataset.means
    stds = full_dataset.stds

    # Print measurement stats
    print("\nMeasurement statistics (original units):")
    for k in keys:
        print(f"  {k}: mean={means[k]:.2f}, std={stds[k]:.2f}")

    best_val_loss = float("inf")
    history = []

    print(f"\nStarting training for {args.epochs} epochs...")
    for epoch in range(1, args.epochs + 1):
        train_loss = train_epoch(model, train_loader, optimizer, criterion, device)
        val_loss, val_mae = validate(model, val_loader, criterion, device, means, stds, keys)

        scheduler.step(val_loss)

        history.append({
            "epoch": epoch,
            "train_loss": train_loss,
            "val_loss": val_loss,
            "val_mae": val_mae,
        })

        mae_str = " | ".join(f"{k}: {val_mae[k]:.2f}" for k in keys)
        print(f"Epoch {epoch:3d}/{args.epochs} | "
              f"train_loss={train_loss:.4f} | val_loss={val_loss:.4f} | {mae_str}")

        # Save best
        if val_loss < best_val_loss:
            best_val_loss = val_loss
            torch.save({
                "epoch": epoch,
                "model_state_dict": model.state_dict(),
                "optimizer_state_dict": optimizer.state_dict(),
                "val_loss": val_loss,
                "means": means,
                "stds": stds,
                "keys": keys,
                "args": vars(args),
            }, out_dir / "best_model.pt")
            print(f"  -> New best model saved (val_loss={val_loss:.4f})")

        # Periodic checkpoint
        if epoch % args.checkpoint_every == 0:
            torch.save({
                "epoch": epoch,
                "model_state_dict": model.state_dict(),
                "optimizer_state_dict": optimizer.state_dict(),
                "val_loss": val_loss,
                "means": means,
                "stds": stds,
                "keys": keys,
                "args": vars(args),
            }, out_dir / f"checkpoint_epoch_{epoch}.pt")

    # Final test evaluation
    print("\nRunning final test evaluation...")
    test_loss, test_mae = validate(model, test_loader, criterion, device, means, stds, keys)
    mae_str = " | ".join(f"{k}: {test_mae[k]:.2f}" for k in keys)
    print(f"Test loss: {test_loss:.4f} | {mae_str}")

    # Save history
    with open(out_dir / "training_history.json", "w") as f:
        json.dump(history, f, indent=2)

    print(f"\nDone! Best model: {out_dir / 'best_model.pt'}")
    print(f"History: {out_dir / 'training_history.json'}")


if __name__ == "__main__":
    main()
